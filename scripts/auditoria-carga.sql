\echo === intervalo de datas (7 dias)
EXPLAIN (ANALYZE) SELECT count(*) FROM log_auditoria WHERE criado_em >= now() - interval '10 days' AND criado_em < now() - interval '3 days';
EXPLAIN (ANALYZE, BUFFERS) SELECT * FROM log_auditoria WHERE criado_em >= now() - interval '10 days' AND criado_em < now() - interval '3 days' ORDER BY criado_em DESC, id DESC LIMIT 20;

