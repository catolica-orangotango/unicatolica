\echo === módulo + ação
EXPLAIN (ANALYZE) SELECT count(*) FROM log_auditoria WHERE modulo = 'modulo1' AND acao = 'ACAO_1_1';
EXPLAIN (ANALYZE, BUFFERS) SELECT * FROM log_auditoria WHERE modulo = 'modulo1' AND acao = 'ACAO_1_1' ORDER BY criado_em DESC, id DESC LIMIT 20;

\echo === entidade afetada
EXPLAIN (ANALYZE) SELECT count(*) FROM log_auditoria WHERE entidade_afetada = 'Entidade2';
EXPLAIN (ANALYZE, BUFFERS) SELECT * FROM log_auditoria WHERE entidade_afetada = 'Entidade2' ORDER BY criado_em DESC, id DESC LIMIT 20;

\echo === detalhes (contém, raro e comum)
EXPLAIN (ANALYZE) SELECT count(*) FROM log_auditoria WHERE detalhes ILIKE '%a1b2c3%';
EXPLAIN (ANALYZE, BUFFERS) SELECT * FROM log_auditoria WHERE detalhes ILIKE '%a1b2c3%' ORDER BY criado_em DESC, id DESC LIMIT 20;
