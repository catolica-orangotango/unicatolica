-- KAN-90, RNF83.1: mede a consulta de logs com 100 mil registros. Roda num Postgres descartável
-- (NUNCA no banco de dev ou de produção): cria uma tabela log_auditoria própria, carrega 100 mil
-- linhas com generate_series, aplica os mesmos índices de infraestrutura-002 e imprime o
-- EXPLAIN ANALYZE de cada filtro sozinho e de todos combinados.
--
--   docker run -d --name auditoria-carga -e POSTGRES_PASSWORD=x postgres:16-alpine
--   docker exec -i auditoria-carga psql -U postgres < scripts/auditoria-carga.sql
--   docker rm -f auditoria-carga

CREATE EXTENSION IF NOT EXISTS pg_trgm;

DROP TABLE IF EXISTS log_auditoria;
CREATE TABLE log_auditoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT,
    modulo VARCHAR(50) NOT NULL,
    acao VARCHAR(100) NOT NULL,
    entidade_afetada VARCHAR(100),
    entidade_id BIGINT,
    detalhes TEXT,
    criado_em TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_log_auditoria_usuario_id ON log_auditoria (usuario_id);
CREATE INDEX idx_log_auditoria_criado_em ON log_auditoria (criado_em);

-- Índices da infraestrutura-002 (copiar daqui para lá se mudar).
DROP INDEX idx_log_auditoria_criado_em;
CREATE INDEX idx_log_auditoria_criado_em_id ON log_auditoria (criado_em DESC, id DESC);
CREATE INDEX idx_log_auditoria_modulo_acao_criado_em ON log_auditoria (modulo, acao, criado_em DESC);
CREATE INDEX idx_log_auditoria_entidade_criado_em ON log_auditoria (entidade_afetada, criado_em DESC);
CREATE INDEX idx_log_auditoria_detalhes_trgm ON log_auditoria USING gin (detalhes gin_trgm_ops);

-- 100 mil registros em 90 dias: 6 módulos, 4 ações por módulo, 5 entidades, detalhes variados.
INSERT INTO log_auditoria (usuario_id, modulo, acao, entidade_afetada, entidade_id, detalhes, criado_em)
SELECT
    CASE WHEN g % 10 = 0 THEN NULL ELSE (g % 500) + 1 END,
    'modulo' || (g % 6),
    'ACAO_' || (g % 6) || '_' || (g % 4),
    CASE WHEN g % 7 = 0 THEN NULL ELSE 'Entidade' || (g % 5) END,
    g % 3000,
    CASE g % 4
        WHEN 0 THEN 'ALUNO -> MODERADOR'
        WHEN 1 THEN 'ativo: true -> false'
        WHEN 2 THEN 'cursoId=' || (g % 40) || ' nome=' || md5(g::text)
        ELSE md5(g::text) || ' ' || md5((g * 7)::text)
    END,
    now() - (g * interval '78 seconds')
FROM generate_series(1, 100000) AS g;
ANALYZE log_auditoria;

\echo === total
SELECT count(*) FROM log_auditoria;

